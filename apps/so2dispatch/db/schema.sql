-- 0034  A pump lot is assembled EC by EC: Assembly & Packing picks ECs of the
-- lot and how many of each, each entry on a day and shift, ticked Assembled
-- with the day — several entries may share out one EC's share of the lot.
-- The lot's assembly_plan_date / assembly_shift / assembled_date on
-- order_ready_lots become a summary of its entries (the next planned one;
-- assembled once all of the lot is). Packing stays lot by lot. Existing
-- lot-wide assembly is carried over as one entry per EC row. Idempotent.
CREATE TABLE IF NOT EXISTS order_lot_assembly (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    lot_row_id     UUID NOT NULL REFERENCES order_ready_lots(id) ON DELETE CASCADE,
    item_id        UUID NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    seq            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    qty            INT  NOT NULL CHECK (qty > 0),
    plan_date      DATE,
    shift          TEXT CHECK (shift IS NULL OR shift IN ('Day', 'Night')),
    assembled_date DATE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_lot_assembly_lot_idx ON order_lot_assembly (lot_row_id, seq);
CREATE INDEX IF NOT EXISTS order_lot_assembly_item_idx ON order_lot_assembly (item_id);
INSERT INTO order_lot_assembly (lot_row_id, item_id, qty, plan_date, shift, assembled_date)
SELECT rl.id, rl.item_id, rl.qty, rl.assembly_plan_date, NULLIF(rl.assembly_shift, ''), rl.assembled_date
  FROM order_ready_lots rl
  JOIN order_items it ON it.id = rl.item_id
 WHERE it.item_type IN ('Pump', 'ROLB')
   AND COALESCE(rl.qty, 0) > 0
   AND (rl.assembled_date IS NOT NULL OR rl.assembly_plan_date IS NOT NULL)
   AND NOT EXISTS (SELECT 1 FROM order_lot_assembly la WHERE la.lot_row_id = rl.id);

