/** A process value the user actually gave. Unfilled numeric fields are often
 *  saved as "0" ("pH 0, 0 C, 0 cP" on many tags) - for pH, temperature,
 *  viscosity and SG a bare 0 means "not entered", not a real reading, and
 *  sending "pH: 0" to the model reads as concentrated acid. */
function given(v: string | null): string | null {
  const s = (v ?? "").trim();
  if (!s) return null;
  return Number(s) === 0 ? null : s;
}

// The enquiry itself (the user message). Media / head / capacity lead -
// they most determine the answer; everything else follows only when given.
function buildPrompt(context: MocAiContext, processData: string): string {
  const head = context.head ? `${context.head} ${context.headUnit || "MWC"}` : "n/a";
  const capacity = context.capacity
    ? `${context.capacity} ${context.capacityUnit ?? ""}`.trim()
    : "n/a";
  // Which ancillary parameters were NOT given, so the model assumes a typical
  // value for the media and labels it (estimated) in one line of the summary.
  const missing: string[] = [];
  if (!given(context.ph)) missing.push("pH");
  if (!given(context.temperatureC)) missing.push("Temperature");
  if (!given(context.viscosityCp)) missing.push("Viscosity");
  const missingClause =
    missing.length > 0
      ? `Not provided: ${missing.join(", ")}. In the summary, note the typical value you assumed for each, labeled (estimated), in one line.\n`
      : "";
  const pumpType = context.pumpType ? context.pumpType : "not specified";
  const vertical = context.pumpType === "Vertical";
  // Wetted status drives material choice, and two components change status with
  // the pump type - so state the groups explicitly, built from the component
  // arrays above (in sync with the on-screen grouping). Stator Rubber is its
  // own elastomer group: a metal answer is useless to the UI's rubber dropdown.
  const wettable = vertical ? VERTICAL_WETTABLE_COMP : HORIZONTAL_WETTABLE_COMP;
  // A close-coupled pump has no bearing housing, so the drive-end component
  // is named for the arrangement the user picked.
  const driveEnd = pumpSupportComponentName(context.pumpSupport);
  const nonWettable = vertical
    ? verticalNonWettableComp(driveEnd)
    : horizontalNonWettableComp(driveEnd);
  const groups = context.pumpType
    ? `This is a ${vertical ? "VERTICAL" : "HORIZONTAL"} pump.\n` +
      `WETTED (media contact - choose for resistance to this media): ${wettable.join(", ")}.\n` +
      `NON-WETTED (structural - choose for strength and cost, do not over-alloy): ${nonWettable.join(", ")}.\n` +
      `ELASTOMER (answer a rubber, not a metal): Stator Rubber.\n`
    : "";
  return (
    `Enquiry - PCP pump. Media: ${context.media}. Pump type: ${pumpType}. Head: ${head}. Capacity: ${capacity}.\n` +
    groups +
    (processData ? `Process data:\n${processData}` : "") +
    missingClause +
    (context.clientRequirementsFile
      ? `Client requirements: SEE THE ATTACHED ${context.clientRequirementsFile.mediaType.startsWith("image/") ? "IMAGE" : "PDF"} in this message. Read it and factor its contents into the recommendation, the same as any other process data - the customer supplied it as part of the enquiry.\n`
      : "") +
    "Assess the media first (mediaAssessment), then record the recommendation."
  );
}

function line(label: string, value: string | null, unit = ""): string {
  return value && value.trim() !== "" ? `${label}: ${value}${unit}\n` : "";
}

function buildProcessData(context: MocAiContext): string {
  return (
    line("pH", given(context.ph)) +
    line("Temperature", given(context.temperatureC), " °C") +
    line("Viscosity", given(context.viscosityCp), " cP") +
    line("SG", given(context.sg)) +
    line("Solids", context.solidPct, "%") +
    line(
      "Particle size",
      context.solidSize,
      context.solidType ? ` mm (${context.solidType})` : " mm",
    )
  );
}

function coerceSuggestions(
  parsed: Partial<Record<string, unknown>>,
  pumpType: string | null,
): MocComponentSuggestions | null {
  // Only the applicable plate is required; the other plate isn't asked for, so
  // it simply comes back empty (get() below returns "" for a missing field).
  if (requiredFieldsFor(pumpType).some((k) => typeof parsed[k] !== "string")) {
    return null;
  }
  const get = (k: keyof MocComponentSuggestions) => {
    const v = parsed[k];
    return typeof v === "string" ? v.trim() : "";
  };
  const out: MocComponentSuggestions = {
    bearingHousing: get("bearingHousing"),
    basePlate: get("basePlate"),
    mountingPlate: get("mountingPlate"),
    tieRod: get("tieRod"),
    nutBolt: get("nutBolt"),
    pumpHousing: get("pumpHousing"),
    rotor: get("rotor"),
    shaft: get("shaft"),
    statorRubber: get("statorRubber"),
    statorSleeve: get("statorSleeve"),
    sealRecommendation: get("sealRecommendation"),
    sealMoc: get("sealMoc"),
    sealRationale: get("sealRationale"),
    summary: get("summary"),
    alternatives: get("alternatives"),
  };
  // Returned as answered — the structural/fastener preference is guidance in
  // the prompt, not an override applied here.
  return out;
}

// Assembles the `content` for the user message. When a client-requirements
// file is attached, it's sent as an image or document content block alongside
// the prompt text - the Anthropic messages API supports both natively for the
// image MIME types (png/jpeg/gif/webp) and PDFs. A missing/unattached file
// falls through to the classic single-string form so the request shape is
// unchanged for the common case.
function buildUserContent(context: MocAiContext, prompt: string):
  | string
  | Array<
      | { type: "text"; text: string }
      | {
          type: "image";
          source: {
            type: "base64";
            media_type: "image/png" | "image/jpeg" | "image/gif" | "image/webp";
            data: string;
          };
        }
      | {
          type: "document";
          source: { type: "base64"; media_type: "application/pdf"; data: string };
        }
    > {
  const file = context.clientRequirementsFile;
  if (!file) return prompt;
  if (file.mediaType.startsWith("image/")) {
    // The list is the exact set Claude's API accepts - the API route already
    // validates the same set on upload, so the cast here is safe.
    return [
      {
        type: "image",
        source: {
          type: "base64",
          media_type: file.mediaType as
            | "image/png"
            | "image/jpeg"
            | "image/gif"
            | "image/webp",
          data: file.base64,
        },
      },
      { type: "text", text: prompt },
    ];
  }
  return [
    {
      type: "document",
      source: { type: "base64", media_type: "application/pdf", data: file.base64 },
    },
    { type: "text", text: prompt },
  ];
}

// --- Anthropic provider (Claude Haiku 4.5) ------------------------------

const ANTHROPIC_MODEL = "claude-haiku-4-5-20251001";
const MOC_TOOL_NAME = "moc_recommendation";

async function getMocAiSuggestionAnthropic(
  context: MocAiContext,
): Promise<MocComponentSuggestions | null> {
  const apiKey = (process.env.ANTHROPIC_API_KEY ?? "").trim();
  if (!apiKey || apiKey.startsWith("REPLACE_")) {
    return null;
  }

  let Anthropic: typeof import("@anthropic-ai/sdk").default;
  try {
    Anthropic = (await import("@anthropic-ai/sdk")).default;
  } catch {
    console.warn("@anthropic-ai/sdk not installed; skipping Anthropic MOC suggestion");
    return null;
  }

  const prompt = buildPrompt(context, buildProcessData(context));

  try {
    const client = new Anthropic({ apiKey });
    const response = await client.messages.create({
      model: ANTHROPIC_MODEL,
      max_tokens: 4000,
      system: MOC_SYSTEM_PROMPT,
      tools: [
        {
          name: MOC_TOOL_NAME,
          description:
            "Records the per-component MOC/elastomer/seal recommendation for a progressive cavity pump.",
          input_schema: {
            type: "object",
            properties: schemaPropertiesFor(context.pumpType, context.pumpSupport),
            required: ["mediaAssessment", ...requiredFieldsFor(context.pumpType)],
          },
        },
      ],
      // Force the single tool call rather than letting Claude reply in free
      // text — this is Claude's equivalent of Gemini's responseSchema: the
      // SDK hands back already-parsed JSON in the tool_use block, so there's
      // no free-text JSON to fish out of a chat-style reply.
      tool_choice: { type: "tool", name: MOC_TOOL_NAME },
      messages: [{ role: "user", content: buildUserContent(context, prompt) }],
    });

    if (response.stop_reason === "refusal") {
      console.warn("Anthropic MOC-suggestion request was refused");
      return null;
    }

    const toolUse = response.content.find((b) => b.type === "tool_use");
    if (!toolUse || toolUse.type !== "tool_use") return null;

    return coerceSuggestions(toolUse.input as Partial<Record<string, unknown>>, context.pumpType);
  } catch (err) {
    console.error("Anthropic MOC-suggestion request failed:", err instanceof Error ? err.message : err);
    return null;
  }
}

