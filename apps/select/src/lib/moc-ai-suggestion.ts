/** Whether the provider has a usable API key configured. Lets the API route
 * report "not configured" (missing/placeholder key) distinctly from "request
 * failed" (key present but the upstream call errored or was blocked), instead
 * of collapsing both into one misleading "not configured" message. The
 * `provider` arg is kept for signature stability though Anthropic is the only
 * option now. */
export function isMocAiProviderConfigured(_provider: MocAiProvider): boolean {
  const key = (process.env.ANTHROPIC_API_KEY ?? "").trim();
  return key !== "" && !key.startsWith("REPLACE_");
}

export async function getMocAiSuggestion(
  context: MocAiContext,
  _provider: MocAiProvider = "anthropic",
): Promise<MocComponentSuggestions | null> {
  return getMocAiSuggestionAnthropic(context);
}
