/**
 * AI-assisted, per-component MOC/elastomer/sealing suggestion for the MOC &
 * Elastomer wizard step. Advisory only, clearly badged as an AI suggestion in
 * the UI, never a substitute for the manual selectors — and never throws: an
 * unset API key, a blocked response, or any request failure just returns
 * null and the caller falls back to "unavailable".
 *
 * Provider: Claude Haiku 4.5 via @anthropic-ai/sdk. Requires ANTHROPIC_API_KEY.
 * Structured output via a forced tool call — the SDK hands back already-parsed
 * JSON in the tool_use block's `input`, no manual JSON.parse needed. (A Google
 * Gemini provider used to be selectable here too; it was removed.)
 *
 * Component breakdown is per the user's spec sheet: non-wettable components
 * (Bearing Housing, Base Plate or Mounting Plate, Tie Rod, Nut & Bolt) and
 * wettable-casting components (Pump Housing, Rotor, Shaft), plus the stator
 * rubber elastomer. The Stator Sleeve joins the non-wettable group on a
 * Horizontal pump and the wettable group on a Vertical one, and the plate is a
 * base plate on Horizontal / a mounting plate on Vertical - both are resolved
 * per request (see schemaPropertiesFor / buildPrompt).
 * MOC_AI_MATERIALS / MOC_AI_ELASTOMERS below are the options offered in the
 * UI's *manual* dropdowns. The prompt gives them to the AI as a PREFERENCE
 * (metals on every metal component, elastomers on the stator rubber) — they
 * are NOT a hard constraint on the AI's own answer. The AI is free to recommend something outside those lists (e.g. an
 * exotic alloy) when the media genuinely calls for it; it's told to say so
 * explicitly rather than being forced into the closest list entry.
 */
