export interface MocAiContext {
  media: string;
  /** Operating-Conditions pump type. Decides whether the stator sleeve is a
   * wetted part (Vertical) or a dry structural one (the Horizontal
   * variants), which changes the material it needs. */
  pumpType: string | null;
  /** Pump Support and Drive Arrangement (Specifications step): "Bearing
   * Housing" or "Close Coupled". Names the drive-end component so the AI
   * specs the part the pump actually has - a close-coupled pump has no
   * bearing housing. Stored on operating_conditions_input.bearing_housing. */
  pumpSupport: string | null;
  head: string | null;
  headUnit: string | null;
  capacity: string | null;
  capacityUnit: string | null;
  ph: string | null;
  temperatureC: string | null;
  viscosityCp: string | null;
  sg: string | null;
  solidPct: string | null;
  solidSize: string | null;
  solidType: string | null;
  /** Legacy free-text extras (kept for old drafts saved before the field
   * became a file upload). Appended to the prompt when present. */
  clientRequirements: string | null;
  /** Client-supplied requirements document (image or PDF) attached to the
   * request as an image or document content block. mediaType is the MIME
   * string the DB has stored, base64 is the raw file bytes. */
  clientRequirementsFile: { mediaType: string; base64: string } | null;
}

export interface MocComponentSuggestions {
  // Non-wettable components
  bearingHousing: string;
  /** Horizontal pump types only - a Vertical pump has a mounting plate
   *  instead, which is a different component (see mountingPlate). */
  basePlate: string;
  /** Vertical pump types only. */
  mountingPlate: string;
  tieRod: string;
  nutBolt: string;
  // Wettable casting components
  pumpHousing: string;
  rotor: string;
  shaft: string;
  // Elastomer
  statorRubber: string;
  // Stator sleeve (wetted on Vertical pumps, structural on Horizontal)
  statorSleeve: string;
  // Sealing
  sealRecommendation: string;
  /** MOC of the recommended seal itself — for a Mechanical Seal: body/metal
   * grade, face pair and O-ring elastomer; for Gland Packing: the packing
   * material. */
  sealMoc: string;
  sealRationale: string;
  // Report content (rendered in the UI's Summary panel and exported to PDF)
  summary: string;
  alternatives: string;
}

