/** LLM provider(s) for the MOC AI recommendation. Only Anthropic (Claude
 * Haiku 4.5) remains — kept as a one-element list so the provider plumbing
 * (persisted mocAiProvider, the "Generated by" label) still works and a
 * second provider can be re-added without reshaping everything. */
export const MOC_AI_PROVIDERS = ["anthropic"] as const;
export type MocAiProvider = (typeof MOC_AI_PROVIDERS)[number];

export interface MocAiContext {
  media: string;
  /** Operating-Conditions pump type. Decides whether the stator sleeve is a
   * wetted part (Vertical) or a dry structural one (the Horizontal
   * variants), which changes the material it needs. */
  pumpType: string | null;
  /** Pump Support and Drive Arrangement (Specifications step): "Bearing
   * Housing" or "Close Coupled". Names the drive-end component so the AI
   * specs the part the pump actually has - a close-coupled pump has no
   * bearing housing. Stored on operating_conditions_input.bearing_housing. */
  pumpSupport: string | null;
  head: string | null;
  headUnit: string | null;
  capacity: string | null;
  capacityUnit: string | null;
  ph: string | null;
  temperatureC: string | null;
  viscosityCp: string | null;
  sg: string | null;
  solidPct: string | null;
  solidSize: string | null;
  solidType: string | null;
  /** Legacy free-text extras (kept for old drafts saved before the field
   * became a file upload). Appended to the prompt when present. */
  clientRequirements: string | null;
  /** Client-supplied requirements document (image or PDF) attached to the
   * request as an image or document content block. mediaType is the MIME
   * string the DB has stored, base64 is the raw file bytes. */
  clientRequirementsFile: { mediaType: string; base64: string } | null;
}

export interface MocComponentSuggestions {
  // Non-wettable components
  bearingHousing: string;
  /** Horizontal pump types only - a Vertical pump has a mounting plate
   *  instead, which is a different component (see mountingPlate). */
  basePlate: string;
  /** Vertical pump types only. */
  mountingPlate: string;
  tieRod: string;
  nutBolt: string;
  // Wettable casting components
  pumpHousing: string;
  rotor: string;
  shaft: string;
  // Elastomer
  statorRubber: string;
  // Stator sleeve (wetted on Vertical pumps, structural on Horizontal)
  statorSleeve: string;
  // Sealing
  sealRecommendation: string;
  /** MOC of the recommended seal itself — for a Mechanical Seal: body/metal
   * grade, face pair and O-ring elastomer; for Gland Packing: the packing
   * material. */
  sealMoc: string;
  sealRationale: string;
  // Report content (rendered in the UI's Summary panel and exported to PDF)
  summary: string;
  alternatives: string;
}

// Fields the tool must always return. The plates are handled separately —
// only ONE exists per pump type (Base on Horizontal, Mounting on Vertical),
// so only that one is asked for (see requiredFieldsFor / schemaPropertiesFor).
const BASE_REQUIRED_FIELDS: (keyof MocComponentSuggestions)[] = [
  "bearingHousing", "tieRod", "nutBolt",
  "pumpHousing", "rotor", "shaft", "statorRubber", "statorSleeve",
  "sealRecommendation", "sealMoc", "sealRationale", "summary", "alternatives",
];

/** The plate that actually exists on this pump type — the only one the model
 * is asked for, so there's no phantom "not present" field to work around. */
function activePlateField(pumpType: string | null): "mountingPlate" | "basePlate" {
  return pumpType === "Vertical" ? "mountingPlate" : "basePlate";
}

function requiredFieldsFor(pumpType: string | null): (keyof MocComponentSuggestions)[] {
  return [...BASE_REQUIRED_FIELDS, activePlateField(pumpType)];
}

// JSON-Schema property map driving Anthropic's tool input_schema (structured
// output).
// Wetted status is THE main driver of material choice, so it is stated on
// every component rather than left for the model to infer from the name: a
// wetted part is picked for resistance to the media, a dry one for strength
// and cost. These strings mirror the two groups the MOC step renders on
// screen (see componentGroupsFor in MocDetailsStep.tsx), so the AI answer and
// the UI grouping agree.
const WETTED =
  "WETTED - in direct contact with the pumped media. Material must resist the media (corrosion/abrasion) at the stated pH, temperature and solids.";
const DRY =
  "NON-WETTED structural part - no media contact. Choose for strength and cost; media resistance does not apply, so do not over-specify an expensive alloy here.";
// Metals the MOC step's dropdowns offer. Preferred so the answer usually maps
// straight onto a dropdown entry, but not mandatory - the media may need
// something else.
const METAL_PREFERENCE =
  "Preferred metals (not mandatory): " +
  MOC_AI_MATERIALS.join(", ") +
  " - another material is fine when the media calls for it; say so explicitly.";
const metal = (status: string) => `${status} ${METAL_PREFERENCE}`;

// Component groups per pump type × wetted status. The prompt's wettable /
// non-wettable listing is built from these arrays instead of hardcoded
// sentences, keeping the prompt small and the two pump-type layouts in sync.
// Two components differ by pump type: the plate (Base on Horizontal, Mounting
// on Vertical) and the Stator Sleeve (dry on Horizontal, wetted on Vertical).
const HORIZONTAL_WETTABLE_COMP = ["Pump Housing", "Rotor", "Shaft"];
const horizontalNonWettableComp = (driveEnd: string) => [
  driveEnd,
  "Base Plate",
  "Tie Rod",
  "Nut & Bolt",
  "Stator Sleeve",
];
// A VERTICAL pump hangs in the liquid, so its tie rods and fasteners sit in
// the media too - they take the SHAFT's MOC, not a structural one. Only the
// bearing housing and the mounting plate stay genuinely dry (per the house
// MOC rules; see STRUCTURAL_MOC_RULES below).
const VERTICAL_WETTABLE_COMP = [
  "Pump Housing",
  "Rotor",
  "Shaft",
  "Stator Sleeve",
  "Tie Rod",
  "Nut & Bolt",
];
const verticalNonWettableComp = (driveEnd: string) => [driveEnd, "Mounting Plate"];

