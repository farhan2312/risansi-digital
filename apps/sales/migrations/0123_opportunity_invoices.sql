-- Invoices raised against a Won opportunity.
--
-- ── Why this is not a write into client_revenue_monthly ─────────
--
-- That is where revenue lives, and it would be the obvious place to put an
-- invoice. It is also a trap. The table is unique on (client_id, month) and
-- BOTH writers upsert with DO UPDATE SET total_value = EXCLUDED.total_value —
-- the comment in risansi-revenue.ts says it plainly: "the latest upload to
-- touch a (client, month) cell owns it."
--
-- So an invoice written there would appear on the dashboards at once, look
-- correct for a few weeks, and then be wiped without trace the next time
-- Finance uploaded that month. The failure would be invisible and the figures
-- would simply be short.
--
-- Invoices therefore live here, and the revenue reads prefer the uploaded
-- figure wherever one exists for that client and month, falling back to these
-- rows where it does not. Nothing is counted twice, and the moment the real
-- upload lands it takes over.
--
-- ── Several per opportunity ─────────────────────────────────────
--
-- A Won order is often dispatched in parts and invoiced in parts, so this is
-- a list rather than three more columns on `opportunities`. invoice_no is
-- unique per opportunity, which catches the same invoice being entered twice
-- without stopping two opportunities legitimately sharing a number across
-- different years.

CREATE TABLE IF NOT EXISTS opportunity_invoices (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id   integer     NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  -- Denormalised deliberately: every revenue read groups by client and month,
  -- and joining back through opportunities on each of them is a join nobody
  -- needs. Set from the opportunity at insert.
  client_id        integer     NOT NULL REFERENCES clients(id),
  invoice_no       text        NOT NULL,
  invoice_date     date        NOT NULL,
  invoice_value_inr numeric(16,2) NOT NULL,
  created_by       text,
  created_at       timestamptz NOT NULL DEFAULT NOW(),
  CONSTRAINT opportunity_invoices_value_positive CHECK (invoice_value_inr > 0),
  CONSTRAINT opportunity_invoices_no_not_blank   CHECK (btrim(invoice_no) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS opportunity_invoices_opp_no_key
  ON opportunity_invoices (opportunity_id, lower(btrim(invoice_no)));

-- The shape every revenue read uses: this client, this month.
CREATE INDEX IF NOT EXISTS idx_opportunity_invoices_client_month
  ON opportunity_invoices (client_id, invoice_date);

-- The latest invoice, mirrored onto the opportunity.
--
-- Exactly how the PO already works: po_number and po_date sit on
-- `opportunities` while the full list lives in opportunity_purchase_orders.
-- The mirror is what lets the Won form show what was already entered when the
-- deal is reopened — without it the three required fields come back blank and
-- have to be typed again, which is the bug this portal keeps re-learning.
--
-- The list remains the source of truth for revenue; these three are for the
-- form.
ALTER TABLE opportunities
  ADD COLUMN IF NOT EXISTS invoice_no        text,
  ADD COLUMN IF NOT EXISTS invoice_date      date,
  ADD COLUMN IF NOT EXISTS invoice_value_inr numeric(16,2);
