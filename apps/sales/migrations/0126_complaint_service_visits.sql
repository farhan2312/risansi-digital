-- A service visit raised off a complaint, for somebody who does not own the
-- client.
--
-- The case: a complaint needs somebody on site, and the nearest TSM is not
-- the account's rep. The complaint handler names who should go and by when;
-- that person plans the actual day themselves and it appears on their
-- activity calendar; they come back with one attachment and the visit is
-- done.
--
-- ── Why this is not a row in `visits` ───────────────────────────
--
-- Because it is explicitly not an ordinary visit. Putting it in `visits`
-- would fold it into the Field Activity KPIs, the 90-day coverage figures,
-- the Visit Reports tab, the Executive Review's attendance table and the new
-- per-rep visit targets — five places that would each have to learn to
-- exclude it, and the first one anybody forgot would quietly credit a rep
-- for somebody else's account.
--
-- A table of its own costs one merge into the calendar query and nothing
-- else can be contaminated by it.
--
-- ── Dates ───────────────────────────────────────────────────────
--
-- target_date is the by-when the complaint handler sets. planned_date is the
-- day the assignee commits to, which is the one the calendar shows and the
-- one that can be missed. Keeping both is the point: "late" means planned
-- after the target, or done after it, and one column cannot say that.

CREATE TABLE IF NOT EXISTS complaint_service_visits (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id   integer     NOT NULL REFERENCES complaints(id) ON DELETE CASCADE,
  -- Denormalised from the complaint so the calendar can show who it is for
  -- without a second join on every cell.
  client_id      integer     REFERENCES clients(id),
  assigned_to    integer     NOT NULL REFERENCES users(id),
  target_date    date,
  planned_date   date,
  status         text        NOT NULL DEFAULT 'Assigned',
  -- The one attachment that closes it. Kept in complaint_attachments under
  -- category 'service_visit' so it reaches Client 360 through the same path
  -- every other complaint document does, rather than a second file store.
  report_attachment_id bigint REFERENCES complaint_attachments(id) ON DELETE SET NULL,
  notes          text,
  assigned_by    text,
  assigned_at    timestamptz NOT NULL DEFAULT NOW(),
  closed_at      timestamptz,
  CONSTRAINT complaint_service_visits_status CHECK (status IN ('Assigned', 'Planned', 'Done', 'Cancelled'))
);

-- The calendar asks "what has this person got on, between these dates".
CREATE INDEX IF NOT EXISTS idx_service_visits_assignee_date
  ON complaint_service_visits (assigned_to, planned_date);
CREATE INDEX IF NOT EXISTS idx_service_visits_complaint
  ON complaint_service_visits (complaint_id);

-- The action that triggers it. Sorted after the other replacement actions
-- and before the softer ones, which is roughly the order of effort.
INSERT INTO complaint_lookups (kind, value, sort_order, is_active, is_user_added)
SELECT 'action_category', 'Service Visit',
       COALESCE((SELECT MAX(sort_order) FROM complaint_lookups WHERE kind = 'action_category'), 0) + 1,
       TRUE, FALSE
 WHERE NOT EXISTS (
   SELECT 1 FROM complaint_lookups WHERE kind = 'action_category' AND value = 'Service Visit');
