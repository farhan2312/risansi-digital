-- 0038  A pump SO's Alignment, lot by lot: each lot names its ECs and how many
-- of each, and has its own Base Plate (Yes / No, status, day, remarks) and
-- Wooden Box (Yes / No, then In house and Bought out each with quantities,
-- status and receipt). The SO's own base plate and wooden box columns stay,
-- kept up to date from its lots. Each SO with an alignment already set starts
-- with Lot 1 holding all of its pump ECs and those values. Same statements in
-- apps/so2dispatch/db/schema.sql. Idempotent and additive.

CREATE TABLE IF NOT EXISTS order_alignment_lots (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id            UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    seq                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- [{item_id, qty}]: the SO's pump ECs in the lot and how many of each.
    ecs                 JSONB NOT NULL DEFAULT '[]'::jsonb,
    base_plate          TEXT CHECK (base_plate IS NULL OR base_plate IN ('Yes', 'No')),
    base_plate_status   TEXT CHECK (base_plate_status IS NULL OR base_plate_status IN ('Pending', 'Fabrication', 'Marking', 'Drilling', 'Painting', 'Manufactured')),
    base_plate_date     DATE,
    base_plate_remarks  TEXT,
    wooden_box          TEXT CHECK (wooden_box IS NULL OR wooden_box IN ('Yes', 'No')),
    -- [{source, required_qty, stock_qty, status, received_date, received_qty, remarks}], a row per way.
    wooden_boxes        JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_alignment_lots_order_idx ON order_alignment_lots (order_id, seq);

-- Each lot's base plate steps, as order_base_plate_history is the SO's.
CREATE TABLE IF NOT EXISTS order_lot_base_plate_history (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    lot_id          UUID NOT NULL REFERENCES order_alignment_lots(id) ON DELETE CASCADE,
    order_id        UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    status          TEXT NOT NULL,
    stage_date      DATE,
    remarks         TEXT,
    prev_status     TEXT,
    prev_date       DATE,
    changed_by      UUID,
    changed_by_name TEXT,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_lot_base_plate_history_lot_idx ON order_lot_base_plate_history (lot_id, changed_at);

-- Lot 1 for each pump SO whose alignment is already set: all its pump ECs, the SO's values.
INSERT INTO order_alignment_lots (order_id, ecs, base_plate, base_plate_status, base_plate_date, base_plate_remarks, wooden_box, wooden_boxes)
SELECT o.id,
       (SELECT COALESCE(jsonb_agg(jsonb_build_object('item_id', it.id, 'qty', it.quantity) ORDER BY it.seq), '[]'::jsonb)
          FROM order_items it WHERE it.order_id = o.id AND it.item_type IN ('Pump', 'ROLB') AND COALESCE(it.quantity, 0) > 0),
       COALESCE(o.base_plate_override,
                CASE WHEN EXISTS (SELECT 1 FROM order_items bpi WHERE bpi.order_id = o.id AND bpi.base_plate = 'Yes') THEN 'Yes' ELSE 'No' END),
       o.base_plate_status, o.base_plate_date, o.base_plate_remarks,
       COALESCE(o.wooden_box_override,
                CASE WHEN o.packing_requirement = 'Wooden Box' THEN 'Yes' WHEN NULLIF(btrim(o.packing_requirement), '') IS NOT NULL THEN 'No' END),
       (SELECT COALESCE(jsonb_agg(jsonb_build_object(
                  'source', wb.source, 'required_qty', wb.required_qty, 'stock_qty', wb.stock_qty, 'status', wb.status,
                  'received_date', to_char(wb.received_date, 'YYYY-MM-DD'), 'received_qty', wb.received_qty, 'remarks', wb.remarks)
                ORDER BY wb.source DESC), '[]'::jsonb)
          FROM order_wooden_boxes wb WHERE wb.order_id = o.id)
  FROM orders o
 WHERE EXISTS (SELECT 1 FROM order_items it WHERE it.order_id = o.id AND it.item_type IN ('Pump', 'ROLB') AND COALESCE(it.quantity, 0) > 0)
   AND (o.base_plate_status IS NOT NULL OR o.base_plate_override IS NOT NULL OR o.wooden_box_override IS NOT NULL
        OR EXISTS (SELECT 1 FROM order_wooden_boxes wb WHERE wb.order_id = o.id))
   AND NOT EXISTS (SELECT 1 FROM order_alignment_lots al WHERE al.order_id = o.id);

-- …and Lot 1 keeps the SO's base plate steps so far.
INSERT INTO order_lot_base_plate_history (lot_id, order_id, status, stage_date, remarks, prev_status, prev_date, changed_by, changed_by_name, changed_at)
SELECT al.id, h.order_id, h.status, h.stage_date, h.remarks, h.prev_status, h.prev_date, h.changed_by, h.changed_by_name, h.changed_at
  FROM order_base_plate_history h
  JOIN order_alignment_lots al ON al.order_id = h.order_id
 WHERE al.seq = (SELECT min(x.seq) FROM order_alignment_lots x WHERE x.order_id = h.order_id)
   AND NOT EXISTS (SELECT 1 FROM order_lot_base_plate_history lh WHERE lh.order_id = h.order_id);
