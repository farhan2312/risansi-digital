-- 0012  Part drawings. Planning (PPC) says whether a pump EC needs part
-- drawings (order_planning.part_drawing, Yes / No) and picks its parts from
-- the pump's parts list, or names others; Drawing marks each part complete.
-- The EC's part drawing reads Pending, Partial complete or Fully complete.
-- Apply to ec_to_dispatch before deploying the code that reads it; also in
-- apps/so2dispatch/db/schema.sql. Idempotent and additive.
ALTER TABLE order_planning ADD COLUMN IF NOT EXISTS part_drawing TEXT;

CREATE TABLE IF NOT EXISTS order_part_drawings (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    item_id         UUID NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    seq             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    section         TEXT,             -- the parts list's section, or Others
    part_no         TEXT,
    part_name       TEXT NOT NULL,
    completed       TEXT,             -- Yes once Drawing has drawn it
    completed_date  DATE,
    remarks         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_part_drawings_item_id_idx ON order_part_drawings (item_id);
DROP TRIGGER IF EXISTS order_part_drawings_set_updated_at ON order_part_drawings;
CREATE TRIGGER order_part_drawings_set_updated_at BEFORE UPDATE ON order_part_drawings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
