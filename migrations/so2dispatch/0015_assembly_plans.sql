-- 0015  Assembly of a pump SO, planned EC by EC: each entry is a day, a
-- shift (Day / Night), an EC and how many of it, ticked Assembled with the
-- day it was. An EC's assembled quantity is the sum of its assembled entries.
-- Apply to ec_to_dispatch before deploying the code that reads it; also in
-- apps/so2dispatch/db/schema.sql. Idempotent and additive.
CREATE TABLE IF NOT EXISTS order_assembly_plans (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id        UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    item_id         UUID NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    seq             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    plan_date       DATE,
    shift           TEXT CHECK (shift IS NULL OR shift IN ('Day', 'Night')),
    qty             INT NOT NULL CHECK (qty > 0),
    assembled       TEXT,
    assembled_date  DATE,
    remarks         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_assembly_plans_order_idx ON order_assembly_plans (order_id, seq);
CREATE INDEX IF NOT EXISTS order_assembly_plans_item_idx ON order_assembly_plans (item_id);
DROP TRIGGER IF EXISTS order_assembly_plans_set_updated_at ON order_assembly_plans;
CREATE TRIGGER order_assembly_plans_set_updated_at BEFORE UPDATE ON order_assembly_plans
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
