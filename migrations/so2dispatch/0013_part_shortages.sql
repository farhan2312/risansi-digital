-- 0013  Shortages. Planning marks the parts a pump EC is short of, from the
-- same parts lists as part drawings (or named under Others).
-- Apply to ec_to_dispatch before deploying the code that reads it; also in
-- apps/so2dispatch/db/schema.sql. Idempotent and additive.
CREATE TABLE IF NOT EXISTS order_part_shortages (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    item_id     UUID NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    section     TEXT,
    part_no     TEXT,
    part_name   TEXT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_part_shortages_item_id_idx ON order_part_shortages (item_id);
