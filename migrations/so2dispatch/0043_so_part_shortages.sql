-- 0043  Spare SO shortages. Planning marks the parts a Spare SO is short of,
-- and how many of each, on the SO as a whole (a pump EC's are on the EC, in
-- order_part_shortages). Same statements in apps/so2dispatch/db/schema.sql.
-- Idempotent and additive.

CREATE TABLE IF NOT EXISTS order_so_part_shortages (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id    UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    section     TEXT,
    part_no     TEXT,
    part_name   TEXT NOT NULL,
    qty         INT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_so_part_shortages_order_id_idx ON order_so_part_shortages (order_id);
